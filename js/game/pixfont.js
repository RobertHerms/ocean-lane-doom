const rampAt = (ramp, i, n) => ramp[Math.min(ramp.length - 1, Math.floor(i * ramp.length / n))];

// ------------------------------------------------------------------ 5×7 ----
export const CH_W = 6, CH_H = 7;   // advance and height of the 5×7 font
export function textWidth(s) { return s.length * CH_W - 1; }
// style: ramp name or array, shadow: colour or null
export function drawText(g, s, x, y, style = 'red', shadow = '#1a0000') {
  const ramp = Array.isArray(style) ? style : RAMPS[style] || RAMPS.red;
  s = String(s).toUpperCase();
  for (const pass of shadow ? [0, 1] : [1]) {
    for (let i = 0; i < s.length; i++) {
      const gl = F57[s[i]] || F57['?'];
      for (let r = 0; r < 7; r++) {
        const bits = gl[r];
        if (!bits) continue;
        g.fillStyle = pass ? ramp[r] : shadow;
        for (let c = 0; c < 5; c++) if (bits & (16 >> c)) g.fillRect(x + i * CH_W + c + (pass ? 0 : 1), y + r + (pass ? 0 : 1), 1, 1);
      }
    }
  }
}
// Text as its own canvas at native resolution (scale it with CSS / drawImage, image-rendering: pixelated).
export function textCanvas(s, style = 'red', shadow = '#1a0000') {
  const c = document.createElement('canvas');
  c.width = Math.max(1, textWidth(String(s)) + 1); c.height = CH_H + 1;
  drawText(c.getContext('2d'), s, 0, 0, style, shadow);
  return c;
}

// ----------------------------------------------------------- big numbers ----
export const BIG_W = 14;   // advance
export function drawBig(g, str, rightX, y) {
  str = String(str);
  let x = rightX - str.length * BIG_W;
  for (const ch of str) {
    const gl = BIG[ch];
    if (gl) {
      for (const pass of [0, 1]) {
        for (let r = 0; r < 16; r++) {
          const row = gl[r];
          for (let c = 0; c < 12; c++) {
            if (row[c] !== '#') continue;
            g.fillStyle = pass ? RAMPS.bigRed[r] : 'rgba(10,0,0,0.85)';
            g.fillRect(x + c + (pass ? 0 : 1), y + r + (pass ? 0 : 1), 1, 1);
          }
        }
      }
    }
    x += BIG_W;
  }
}

// ---------------------------------------------------------- small numbers ----
export function drawSmall(g, str, rightX, y, color = '#ffd24a', shadow = 'rgba(0,0,0,0.6)') {
  str = String(str);
  let x = rightX - str.length * 4;
  for (const ch of str) {
    const gl = SMALL[ch];
    if (gl) for (const pass of shadow ? [0, 1] : [1]) {
      g.fillStyle = pass ? color : shadow;
      for (let r = 0; r < 6; r++) for (let c = 0; c < 4; c++) if (gl[r][c] === '#') g.fillRect(x + c + (pass ? 0 : 1), y + r + (pass ? 0 : 1), 1, 1);
    }
    x += 4;
  }
}
export function drawTiny(g, str, x, y, color, shadow) {
  for (const ch of str) {
    const gl = TINY[ch];
    if (gl) for (const pass of shadow ? [0, 1] : [1]) {
      g.fillStyle = pass ? color : shadow;
      for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (gl[r][c] === '#') g.fillRect(x + c + (pass ? 0 : 1), y + r + (pass ? 0 : 1), 1, 1);
    }
    x += 4;
  }
}

// Large menu / title lettering: the 5×7 font blown up, each font pixel a block of k×k, a vertical colour
// ramp over the whole glyph and a dark outline. bevel: light the glyph's top / left edges and shade its bottom /
// right ones (only where they face outside the letter), for a carved look at k ≥ 3.
export function bigText(s, { k = 3, ramp = RAMPS.red, outline = '#2a0000', spacing = 1, bevel = false } = {}) {
  s = String(s).toUpperCase();
  const adv = (5 + spacing) * k;
  const w = s.length * adv - spacing * k + 2, h = 7 * k + 2;
  const c = document.createElement('canvas');
  c.width = w + 1; c.height = h + 1;
  const g = c.getContext('2d');
  const cells = [];
  for (let i = 0; i < s.length; i++) {
    const gl = F57[s[i]] || F57['?'];
    const on = (r, col) => r >= 0 && r < 7 && col >= 0 && col < 5 && (gl[r] & (16 >> col)) !== 0;
    for (let r = 0; r < 7; r++) for (let col = 0; col < 5; col++) {
      if (on(r, col)) cells.push([1 + i * adv + col * k, 1 + r * k, r, !on(r - 1, col), !on(r, col - 1), !on(r + 1, col), !on(r, col + 1)]);
    }
  }
  // outline + drop shadow
  g.fillStyle = outline;
  for (const [x, y] of cells) g.fillRect(x - 1, y - 1, k + 2, k + 2);
  g.fillStyle = 'rgba(0,0,0,0.55)';
  for (const [x, y] of cells) g.fillRect(x + 1, y + 1, k + 1, k + 1);
  for (const [x, y, r] of cells) {
    for (let yy = 0; yy < k; yy++) {
      g.fillStyle = rampAt(ramp, r * k + yy, 7 * k);
      g.fillRect(x, y + yy, k, 1);
    }
  }
  if (bevel && k >= 3) {
    for (const [x, y, , top, left, bottom, right] of cells) {
      g.fillStyle = 'rgba(255,240,220,0.42)';
      if (top) g.fillRect(x, y, k, 1);
      if (left) g.fillRect(x, y + (top ? 1 : 0), 1, k - (top ? 1 : 0));
      g.fillStyle = 'rgba(20,0,0,0.38)';
      if (bottom) g.fillRect(x, y + k - 1, k, 1);
      if (right) g.fillRect(x + k - 1, y, 1, k - (bottom ? 1 : 0));
    }
  }
  return c;
}
